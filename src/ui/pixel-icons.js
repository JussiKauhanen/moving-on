export function pixelIcon(name, className = "") {
  const rows = (ICONS[name] || ICONS.gardener).trim().split("\n");
  let rects = "";
  rows.forEach((row, y) =>
    [...row.trim()].forEach((ch, x) => {
      if (ch === "#")
        rects += `<rect x="${x}" y="${y}" width="1" height="1"/>`;
      else if (ch === "+")
        rects += `<rect class="accent" x="${x}" y="${y}" width="1" height="1"/>`;
    }),
  );
  return `<svg class="pixel-icon ${className}" viewBox="0 0 12 12" shape-rendering="crispEdges" aria-hidden="true" fill="currentColor">${rects}</svg>`;
}
